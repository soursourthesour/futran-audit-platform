@pytest.mark.parametrize("role,action,expected", ROWS, ids=[f"{r.value}-{a.value}" for r, a, _ in ROWS])
def test_matrix_rows_match_spec(role, action, expected):
    assert MATRIX.get(role, {}).get(action, S.NONE) == expected


@pytest.mark.parametrize("action", [A.RECORD_FINDINGS, A.APPROVE_FINDINGS, A.SET_FINAL_TIER, A.OVERRIDE_FINAL_TIER, A.SCORE_SYSTEM, A.VERIFY_SYSTEM_ANSWERS])
def test_admin_never_judgment(action):
    assert MATRIX[R.ADMIN].get(action, S.NONE) == S.NONE


def test_client_roles_never_get_all_or_assigned():
    from app.policy.roles import CLIENT_ROLES

    for role in CLIENT_ROLES:
        for action, scope in MATRIX.get(role, {}).items():
            assert scope not in (S.ALL, S.ASSIGNED), (role, action)
